// =============================================================================
// 文件名: interface_GN560.h
// 描  述: GN560欺骗信号测向DLL的外部接口头文件
// 功  能: 定义DLL导出函数和GN560专用数据结构，供外部程序（如主控软件）调用。
//         本文件是DLL与外部程序之间的桥梁，外部程序通过包含本头文件并使用
//         导出函数来创建、配置、运行和销毁测向引擎实例。
//
// 核心数据结构:
//   DJDFResult    - 欺骗干扰测向结果，包含多系统多频点的卫星角度信息
//   RangData      - 测距原始数据，包含两个通道（Port One/Two）的卫星观测数据
//   DeceptiveResult - 欺骗检测结果，包含被判定为欺骗的卫星信息及切刀顺序
//
// 导出接口函数（共6个）:
//   createDeceiveDoa()       - 创建测向引擎实例，返回实例句柄(id)
//   initDeceiveDoa()         - 初始化指定实例
//   setDataDeceiveDoa()      - 向指定实例送入原始观测数据
//   getAngleDeceiveDoa()     - 从指定实例获取测向结果
//   setDeceptiveResult()     - 设置欺骗检测结果和切刀顺序
//   releaseDeceiveDoa()      - 释放指定实例，释放所有资源
//
// 使用流程:
//   1. int id = createDeceiveDoa();            // 创建实例
//   2. initDeceiveDoa(id, "/Radius.txt");      // 初始化
//   3. setDeceptiveResult(id, decResult);      // 设置欺骗检测结果（可选，有欺骗时才调用）
//   4. setDataDeceiveDoa(id, &rangData, len);  // 送入观测数据（可多次调用）
//   5. getAngleDeceiveDoa(id, djdfResult);     // 获取测向结果
//   6. releaseDeceiveDoa(id);                  // 释放实例
//
// GN560 与通用接口的差异:
//   - 专为 GN560 定向天线平台设计，数据结构中包含了切刀(Cut Sequence)相关信息
//   - DeceptiveResult 中增加了 cutSequencenum 和 cutSequence 字段用于天线切换
//   - 测向结果 DJDFResult 复用基类的 SatelliteAngle/SatelliteData 结构
// =============================================================================

#include "SpoofingDoaGN560.h"
#include "../publicFunctionDoa/publicFunctionDoa.h"
#include <iostream>
#pragma once
#pragma pack(1)

// =============================================================================
// 结构体: DJDFResult (Deceptive Jamming Direction Finding Result)
// 描  述: 欺骗干扰测向结果。存储测向引擎计算出的各频点来波方向角度信息。
//         每个频点对应一个 SatelliteAngle 记录，包含该频点下所有被判定为
//         欺骗信号的卫星的角度、载噪比和测向质量等信息。
// 字  段:
//   i_Count        - 有效结果个数，即 i_SatelliteAngle 数组中实际有效的元素数
//   i_SatelliteAngle[24] - 测向结果数组，最多支持24个频点/系统组合的结果
// =============================================================================
struct DJDFResult
{
    int i_Count;                          // 有效测向结果个数
    SatelliteAngle i_SatelliteAngle[24];  // 各频点/系统的测向结果数组
};

// =============================================================================
// 结构体: RangData (Range Data - 测距数据)
// 描  述: 单帧原始卫星观测数据。包含两个通道（Port One 和 Port Two）的卫星
//         观测信息。在定向天线欺骗测向场景中，通常一个通道连接当前工作天线，
//         另一个通道连接参考天线，通过两个通道的载波相位差进行测向。
// 字  段:
//   i_PortOneNum      - 第一通道接收到的卫星个数
//   i_PortOne[500]    - 第一通道中各卫星的观测数据（PRN/系统/频点/伪距/载噪比/相位/多普勒）
//   i_PortTwoNum      - 第二通道接收到的卫星个数
//   i_PortTwo[500]    - 第二通道中各卫星的观测数据
// 注  意: 数组大小 500 为最大容量上限，实际有效数量由 i_PortOneNum/i_PortTwoNum 指定
// =============================================================================
struct RangData
{
    int i_PortOneNum;              // 第一通道（当前天线通道）的卫星个数
    SatelliteData i_PortOne[500];  // 第一通道卫星数据数组

    int i_PortTwoNum;              // 第二通道（参考天线通道）的卫星个数
    SatelliteData i_PortTwo[500];  // 第二通道卫星数据数组
};

// =============================================================================
// 结构体: DeceptiveResult
// 描  述: 欺骗检测结果。由外部欺骗检测模块传入，告知测向引擎哪些卫星/频点
//         被判定为欺骗信号，以及天线切刀的顺序。测向引擎仅对欺骗检测判定为
//         欺骗的信号进行测向（当 m_Screen_detection_Flag = 1 时）。
// 字  段:
//   strnum          - 被判定为欺骗的频点数量
//   allresult[24]   - 各频点的欺骗检测详细结果（系统/频点/角度/卫星号等）
//   cutSequencenum  - 天线切刀标识：0 表示未进行切刀（单天线工作），
//                     8 表示进行了切刀操作（切换天线进行测向）
//   cutSequence[20] - 切刀天线顺序码，固定大小数组。每个元素表示一刀对应的天线编码，
//                     例如 {1,2,1,3,...} 表示第1刀用天线1和2的相位差，第2刀用天线1和3的相位差
//                     在定向天线模式下，通过切换不同天线对来获取不同方向的相位差信息
// =============================================================================
struct DeceptiveResult
{
    int strnum;                          // 返回的数量：被判定为欺骗的频点/系统组合个数
    SingleDeceptiveResult allresult[24]; // 返回的干扰：各频点欺骗检测详细结果
    int cutSequencenum;                  // 是否切天线转欺骗测向,0为不切，8为切
    int cutSequence[20];                 // 固定大小的切刀天线码数组（每刀对应的天线对编码）
};
