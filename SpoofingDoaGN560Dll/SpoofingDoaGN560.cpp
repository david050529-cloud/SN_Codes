// =============================================================================
// 文件名: SpoofingDoaGN560.cpp
// 描  述: GN560设备欺骗信号测向类的 Init() 方法实现
// 功  能: 完成 GN560 平台所有初始化参数的配置。该文件是 GN560 与基类
//         SpoofingDoa 之间差异的集中体现，所有 GN560 特有参数均在此设置。
//
// GN560 与基类默认配置的关键差异：
//  1. 天线类型: 定向天线 (m_antnenaType = 1)
//     - 定向天线意味着不同方向的天线增益不同，需要根据载噪比选择合适的天线进行测向
//     - 全向天线（基类默认）在所有方向增益相同，测向时使用全部天线
//
//  2. 天线数量: 7 个阵元 (m_AntennaNum = 7)
//     - GN560 使用 7 阵元的均匀圆阵 (UCA)
//
//  3. 测向算法: 相关干涉仪 (m_Doa_Arithmetic = 1)
//     - 相关干涉仪通过将测量相位差与理论相位差进行相关匹配来估计来波方向
//
//  4. 伪谱积分: 启用 (m_PseudoSpectrum_Flag = 1)
//     - 对多帧数据的伪谱进行积分累加，提高测向稳定性和精度
//
//  5. 欺骗检测筛选: 启用 (m_Screen_detection_Flag = 1)
//     - 根据欺骗检测的结果筛选数据，仅对被判定为欺骗的信号进行测向
//
//  6. 检测阈值: 使用特定的连续检测帧数、相位差阈值等参数
//
//  7. 初始化参数设置顺序的重要性：
//     - 所有派生类特有参数必须在调用 SpoofingDoa::Init() 之前设置完成
//     - 因为 SpoofingDoa::Init() 会读取这些参数进行后续初始化操作（如读配置文件、初始化理论相位差等）
//     - setThresholdDetectionDoa() 必须在 SpoofingDoa::Init() 之后调用，
//       因为它依赖 Init() 中初始化的频点信息
// =============================================================================

#include "SpoofingDoaGN560.h"
using namespace std;

// =============================================================================
// 方法名: Init
// 参  数: adr - 配置文件路径字符串（通常为 "/Radius.txt"），包含各频点的阵列半径信息
// 返回值: 无
// 描  述: GN560 平台的完整初始化流程：
//
//         第一步: 保存配置文件路径到 m_Radr
//         第二步: 设置 GN560 特有参数（天线类型、数量、算法选择等）
//                注意: 这些参数必须在调用基类 Init() 之前设置
//         第三步: 调用 SpoofingDoa::Init() 进行通用初始化
//                 - 读取配置文件（阵列半径等）
//                 - 初始化各频点频率信息
//                 - 初始化理论相位差数据
//                 - 初始化仿真阵列流型数据
//         第四步: 调用 setThresholdDetectionDoa() 为各频点设置欺骗检测阈值
//                 参数说明: (连续检测帧数阈值, 相位差阈值, 卫星系统, 卫星频点)
//                 这里设置了 5 个频点的阈值，覆盖 GPS L1(C/A)、BDS B1I、BDS B1C 等
//
//  参  数  详  解:
//         m_AntennaNum = 7          阵列天线阵元个数，GN560 使用 7 阵元均匀圆阵
//         m_Angle_Threshold = 3     角度合并阈值(度)，±3度以内的测向结果视为同一方向
//         m_antnenaType = 1         天线类型：0=全向天线, 1=定向天线 (GN560为定向天线)
//         m_PseudoSpectrum_Flag = 1 伪谱积分开关：0=不积分, 1=积分（累加多帧提高精度）
//         m_Save_Original_Flg = 0   原始数据保存标志：0=不保存, 1=保存（用于调试回放）
//         m_Doa_Arithmetic = 1      测向算法选择：1=相关干涉仪, 2=幅相法, 3=干涉仪+仿真数据
//         m_Virtual_Flag = 0        虚拟阵列开关：0=不加入, 1=加入（扩展阵列孔径）
//         m_Screen_detection_Flag=1 欺骗检测筛选：1=仅对被判定为欺骗的信号测向, 0=全部测向
//         m_getUseAntennaBySnr_Flag=0 载噪比选天线：0=不利用, 1=根据载噪比确定测向天线序号
//         m_LogFile              日志文件路径前缀
//         m_Snr_Threshold = 32.0  载噪比阈值(dB-Hz)，低于此值的信号不参与测向计算
//         m_Delete_Prn_Flag = 0   缺刀数据删除标志：0=不删除, 1=删除有一刀缺失的数据
//         m_Doa_Cut_Num = 3       用于测向的切刀次数（定向天线模式下使用较少刀数）
//         m_Doa_Cut_min_Num = 2   测向所需最少切刀数（每刀至少需要这么多相位差数据）
//         m_Detection_Threshold_Num = 4  连续检测为欺骗的帧数阈值
//         m_Accumulate_multiplier = 0.95 伪谱积分衰减因子（值越大历史信息保留越多）
//         m_Detection180_Qulity_Threshold = 1.5  跳半周修复后的测向质量阈值
//
//  setThresholdDetectionDoa 参数说明:
//         参数1: threshold - 连续多少帧检测为欺骗信号才确认告警
//         参数2: phsThreshold - 相位差阈值，-1 表示不启用相位差检测
//         参数3: sys - 卫星系统编号 (例如 5=BDS, 1=GPS)
//         参数4: type - 卫星频点编号 (例如 0,2,4,12,17,19 分别对应不同频点)
//
//  GN560 设置了以下频点的检测阈值:
//         (5,-1,4,17): BDS系统, 频点17, 连续5帧确认, 不使用相位差检测
//         (5,-1,4,0):  BDS系统, 频点0,  连续5帧确认, 不使用相位差检测
//         (5,-1,4,19): BDS系统, 频点19, 连续5帧确认, 不使用相位差检测
//         (5,-1,4,2):  BDS系统, 频点2,  连续5帧确认, 不使用相位差检测
//         (5,-1,4,12): BDS系统, 频点12, 连续5帧确认, 不使用相位差检测
// =============================================================================
void SpoofingDoaGN560::Init(const char *adr)
{
  string adr2(adr);
  m_Radr = adr2;                          // 保存配置文件路径，后续用于读取阵列半径等参数

  // ========== GN560 特有参数设置（必须在基类 Init() 之前设置） ==========
  m_AntennaNum = 7;                      // 阵列中的天线个数（GN560使用7阵元均匀圆阵UCA）
  m_Angle_Threshold = 3;                 // 同一方向的阈值，单位度，在±m_Angle_Threshold度的范围内被认为是同一方向
  m_antnenaType = 1;                     // 天线类型，0 为全向天线，1 为定向天线（GN560为定向天线）
  m_PseudoSpectrum_Flag = 1;             // 是否进行伪谱积分,0 不积分,1 积分（GN560启用积分提高稳定性）
  m_Save_Original_Flg = 0;               // 是否保存原始数据 0 不保存  1 保存
  m_Doa_Arithmetic = 1;                  // 测向所用的算法；1 相关干涉仪；2 幅相法 3 相关干涉仪+阵列仿真数据
  m_Virtual_Flag = 0;                    // 是否加入虚拟阵列（GN560不加入）
  m_Screen_detection_Flag = 1;           // 是否根据欺骗检测结果筛选数据，1 筛选  0 不筛选
  m_getUseAntennaBySnr_Flag = 0;         // 是否利用载噪比确定用于测向的天线序号 1 利用 0 不利用
  string m_LogFile = "/spoofingDoaLog_"; // 日志文件路径前缀（所有日志文件以此开头）
  m_Snr_Threshold = 32.0;                // 载噪比阈值(dB-Hz)，若载噪比小于该值则不用于计算
  m_Delete_Prn_Flag = 0;                 // 是否删除其中有一刀数据未收到的卫星，0 不删除
  m_Doa_Cut_Num = 3;                     // 用于测向的切刀次数（定向天线模式下减少刀数以适应实际工况）
  m_Doa_Cut_min_Num = 2;                 // 测向所需的最少切刀数（每刀至少需要这么多相位差数据）
  m_Detection_Threshold_Num = 4;         // 连续检测帧数阈值：连续4帧均检测为欺骗才确认
  m_Accumulate_multiplier = 0.95;        // 伪谱积分衰减因子：当前帧权重0.05，历史累积权重0.95
  m_Detection180_Qulity_Threshold = 1.5; // 跳半周修复后的质量阈值：修复后的测向质量需大于此值才采纳

  // ========== 调用基类通用初始化 ==========
  // 基类 Init() 会：
  // 1. 根据 m_Radr 读取配置文件获取各频点的阵列半径
  // 2. 初始化各卫星系统/频点对应的频率信息
  // 3. 根据 m_Doa_Arithmetic 初始化对应的理论相位差或仿真阵列流型
  // 4. 初始化检测记录队列、校正数据等
  SpoofingDoa::Init();

  // ========== 设置各频点的欺骗检测阈值 ==========
  // 参数: (连续检测帧数, 相位差阈值, 卫星系统, 卫星频点)
  // phaseThreshold = -1 表示该频点不使用相位差进行欺骗检测
  // 以下为各 BDS (北斗) 频点设置检测阈值，均使用连续5帧确认，不使用相位差检测

  setThresholdDetectionDoa(5, -1, 4, 17); // BDS系统频点17：连续5帧确认欺骗
  setThresholdDetectionDoa(5, -1, 4, 0);  // BDS系统频点0：连续5帧确认欺骗
  setThresholdDetectionDoa(5, -1, 4, 19); // BDS系统频点19：连续5帧确认欺骗
  setThresholdDetectionDoa(5, -1, 4, 2);  // BDS系统频点2：连续5帧确认欺骗
  setThresholdDetectionDoa(5, -1, 4, 12); // BDS系统频点12：连续5帧确认欺骗
}
