/************************************************************************/
/* 文件名称: interface_suppress_GN560.h
/* 文件描述: GN560项目压制干扰测向DLL的导出接口声明
/*
/* 功能概述:
/*   本文件声明了SuppressDoaGN560动态链接库的所有C语言导出接口函数。
/*   该DLL封装了GN560项目专用的压制干扰测向算法，供外部程序（如C#、LabVIEW、
/*   MATLAB等）通过P/Invoke或动态加载方式调用。
/*
/* GN560与基础版SuppressDoa的主要区别:
/*   1. 单通道测向：GN560仅支持单通道模式（4次移相），基础版支持单通道/多通道切换
/*   2. 数据类型：GN560接口使用double*传递IQ数据，内部转换为short；基础版直接使用short*
/*   3. 采样点数：GN560创建时仅需指定采样点数，起止点数在setData时动态设置；
/*      基础版创建时即需指定startPointNum和endPointNum
/*   4. 频宽参数：GN560的初始化需要传入采样带宽(bandwidth)，用于计算功率系数
/*   5. 单通道误差系数：GN560初始化需传入移相误差系数文件路径(adr)，用于校正
/*      单通道的四次移相相位误差
/*   6. 粗测向角度：GN560的setData接口预留了粗测向角度参数(briefAngle)，
/*      但当前版本强制设为400度（即不使用粗测向引导）
/*   7. 测向结果：GN560提供单信号(getAngleSuppressDoa)和多信号
/*      (getMuiltAngleSuppressDoa)两种结果获取方式；基础版统一返回多信号结果数组
/*   8. 项目标识：底层SuppressDoa类默认项目标志为GN560(m_Project_flg=GN560)，
/*      使用7阵元均匀圆阵，切刀序列为相邻天线对{{1,2},{2,3}...{7,1}}
/*   9. 无校正数据：GN560接口不包含setCorrectionDataSuppressDoa函数，
/*      因为单通道模式下无需设置多通道校正数据
/*
/* 调用流程:
/*   1. createSuppressDoa  -> 创建测向对象，获取对象ID
/*   2. initSuppressDoa    -> 初始化测向参数（频率、误差系数文件、带宽）
/*   3. setDataSuppressDoa -> 设置IQ测向数据（可多次调用，重复测向）
/*   4. getAngleSuppressDoa 或 getMuiltAngleSuppressDoa -> 获取测向结果
/*   5. releaseSuppressDoa -> 释放对象资源
/*
/* 创建时间: 2024年
/* 修改记录:
/************************************************************************/

#include "../SuppressDoaDll/SuppressDoa.h"
#include"../publicFunctionDoa/publicFunctionDoa.h"
#include <iostream>

